"""Content Tool-informed reader-first editorial contract for Autopilot.

The reader must learn what happened BEFORE being asked to appreciate a trend.
The source is the only factual authority; examples and editorial angles provide
style and choice of emphasis, never extra facts.
"""

from __future__ import annotations


READER_FIRST_NEWSROOM_RULES = """
РЕДАКЦІЙНИЙ КОНТРАКТ ЗРОЗУМІЛОСТІ (за принципами Content Tool):
1. ПЕРШЕ РЕЧЕННЯ: конкретна новина. Хто (людина, установа, компанія), що зробив/що сталося і з чим. Не починай із філософії, загальних трендів чи рекламного вступу.
2. Не припускай, що читач знає англомовні назви, абревіатури чи професійний жаргон. Коли SOURCE дає розшифрування або роль, поясни її одним коротким природним зворотом біля першої згадки. Без підтвердженого пояснення не вигадуй його.
3. КОЖЕН наступний абзац логічно пояснює перший: конкретний механізм, результат або важливий для читача контекст З ТОГО Ж ДЖЕРЕЛА. Не склеюй в одну причинно-наслідкову історію розрізнені тези, бренди або цифри.
4. Висновок, оцінка, парадокс чи твердження про зміну суспільства не стають фактом лише тому, що звучать переконливо. Без прямої опори на SOURCE прибери такий висновок. Пряма фактична новина важливіша за «красивий» фінал.
5. Пиши сучасною літературною українською. Просте зрозуміле слово краще за непотрібну кальку або рекламний англіцизм. Назви брендів, точні числа, цитати й підтверджені зв'язки збережи.
6. Два короткі інформативні абзаци кращі за три довгі абзаци «води». Не вигадуй другий факт для обсягу. Пояснення має стосуватися тільки підтвердженого змісту.
7. ANGLE, EDITORIAL MEMORY та CHANNEL RULES впливають лише на подачу. Якщо вони сперечаються з SOURCE, перемагає SOURCE.
Це внутрішні правила. Не виводь їх у текст поста.
""".strip()


COMMERCIAL_READER_RULES = """
ДЛЯ МАРКЕТИНГОВОГО/КОМЕРЦІЙНОГО КАНАЛУ:
- Відповідай одразу, хто випустив продукт/кампанію, що конкретно зроблено, і в чому незвична механіка. Якщо учасників кілька, не приписуй дії одного іншому.
- Не перетворюй новину на модне есе про «нову культуру», «парадокс», «маркери», «поворот епохи» або «споживчі коди», якщо першоджерело цього не доводить.
- Порівняння й статистику подавай тільки з указаним у SOURCE об'єктом, періодом і джерелом вимірювання. Не притягуй віддалені цифри до новини штучним переходом.
- Жаргон заміни звичайними українськими словами, коли зміст зберігається: передзамовлення, нова партія, сумка, повторний випуск.
""".strip()


MONITORING_READER_RULES = """
ДЛЯ ГРОМАДСЬКОЇ/НОВИННОЇ СТРІЧКИ:
- Першими мають бути суть події, адресат і підтверджений результат; далі конкретні дати, місце, умови та контакти, якщо вони є.
- Не перетворюй повідомлення адміністрації на абстрактну статтю або оцінку. Не пропускай практичні дії, необхідні читачеві.
- Окремо позначені плани, припущення та непідтверджені дані ніколи не перетворюй на звершені факти.
""".strip()


FINAL_READER_REVIEW = """
КОНТРОЛЬ РЕДАКТОРА ПЕРЕД ПУБЛІКАЦІЄЮ:
- Прочитай текст так, ніби читач не бачив джерела. Після першого речення має бути ясно, що саме сталося і хто є головним учасником.
- Перевір роль кожної установи/бренду та причинні зв'язки між абзацами. Не допускай випадкового переліку назв, узагальнень і чисел.
- Якщо чернетка граматично правильна, але незрозуміла, ПЕРЕБУДУЙ її з SOURCE навколо однієї новини, а не просто відполіруй слова.
- Перевір кожне твердження на SOURCE: не додавай нових фактів, відсотків, причин, дат, учасників, спорідненості або наслідків.
- Прибери кальки, штучний пафос, рекламний тон і абстрактні висновки без перевірюваних деталей.
- Віддай лише готовий природний український текст, без аудиту чи приміток.
""".strip()


def writer_reader_rules(*, monitoring: bool, commercial: bool) -> str:
    extra = MONITORING_READER_RULES if monitoring else (
        COMMERCIAL_READER_RULES if commercial else ""
    )
    return READER_FIRST_NEWSROOM_RULES + ("\n" + extra if extra else "")


def final_reader_rules(*, monitoring: bool, commercial: bool) -> str:
    extra = MONITORING_READER_RULES if monitoring else (
        COMMERCIAL_READER_RULES if commercial else ""
    )
    return FINAL_READER_REVIEW + ("\n" + extra if extra else "")
